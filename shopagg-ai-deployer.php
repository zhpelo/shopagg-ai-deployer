shopagg_ai_deployer_maybe_upgrade();
shopagg_ai_deployer_admin_bootstrap();

add_action('rest_api_init', 'shopagg_ai_deployer_register_routes');

add_filter('rest_post_dispatch', static function ($response, WP_REST_Server $server, WP_REST_Request $request) {
    if (!str_starts_with($request->get_route(), '/' . SHOPAGG_AI_DEPLOYER_REST_NS . '/')) {
        return $response;
    }
    if (!defined('DONOTCACHEPAGE')) {
        define('DONOTCACHEPAGE', true);
    }
    do_action('litespeed_control_set_nocache', 'SHOPAGG Deployer API');
    if (is_object($response) && method_exists($response, 'header')) {
        $response->header('Cache-Control', 'private, no-store, no-cache, must-revalidate, max-age=0');
        $response->header('Pragma', 'no-cache');
        $response->header('Expires', '0');
        $response->header('Vary', 'X-ShopAgg-AI-Deployer-Key');
        $response->header('X-LiteSpeed-Cache-Control', 'no-cache');
    }
    return $response;
}, 10, 3);

